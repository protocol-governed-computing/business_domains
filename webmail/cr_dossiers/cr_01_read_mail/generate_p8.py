"""Write this dossier's P8 from its P7.

The mandate is derived, not decided: each new artifact is built after the new artifacts it names,
and every field is read from P7's registers. Writes `p8_authoring_mandate_webmail_mailbox_v0.md`.

    python generate_p8.py
"""

import re
from collections import Counter
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
P7 = HERE / "p7_design_intent_webmail_mailbox_v0.md"
OUT = HERE / "p8_authoring_mandate_webmail_mailbox_v0.md"


def registers(path):
    return yaml.safe_load(re.search(r"```yaml\n(.*?)```", path.read_text(), re.S).group(1))


def short(code):
    return code.split("::")[-1]


def main():
    doc = registers(P7)
    r = doc["registers"]
    domain, sub = doc["document"]["domain"], doc["document"]["subdomain"]
    new = [a["code"] for a in r["new_artifacts"]]
    family = {a["code"]: a["family"] for a in r["new_artifacts"]}
    full = {short(c): c for c in new}

    # What each new artifact names among the other new artifacts.
    deps = {c: set() for c in new}
    for row in r["cc_composition"]:
        if row["capability"] in deps:
            deps[row["cc_code"]].add(row["capability"])
    for row in r["execution_topology"]:
        for name in [row.get("runs"), row["node"]]:
            if name and short(name) in full and full[short(name)] != row["workflow"]:
                deps[row["workflow"]].add(full[short(name)])
    for row in r["artifact_properties"]:
        values = row["value"] if isinstance(row["value"], list) else [row["value"]]
        for v in values:
            if isinstance(v, str) and v in deps and v != row["artifact"]:
                deps[row["artifact"]].add(v)
    for row in r["rb_declarations"]:
        deps[row["rb_code"]].add(row["storage_structure"])
        deps[row["binds_wf"]].add(row["rb_code"])

    # Waves: an artifact is built once everything it names is built.
    wave, built = {}, set()
    n = 0
    while len(built) < len(new):
        n += 1
        ready = [c for c in new if c not in built and deps[c] <= built]
        if not ready:
            raise SystemExit(f"cycle among {sorted(set(new) - built)}")
        for c in ready:
            wave[c] = n
        built |= set(ready)

    order = sorted(new, key=lambda c: (wave[c], new.index(c)))
    build_order = [{"wave": str(wave[c]), "step": str(i), "code": c, "action": "NEW",
                    "subdomain": sub, "depends_on": sorted(deps[c]) or None}
                   for i, c in enumerate(order, 1)]

    # The longest chain of dependencies, ending at a workflow.
    def chain(c):
        return max(([*chain(d), c] for d in deps[c]), key=len, default=[c])
    longest = max((chain(c) for c in new), key=len)

    counts = Counter(family[c] for c in new)
    desc = ", ".join(f"{k} {f}" for f, k in sorted(counts.items(), key=lambda x: (-x[1], x[0])))

    fields = {c: [] for c in new}
    for row in r["interface_fields"]:
        if row["artifact"] in fields:
            fields[row["artifact"]].append((row["direction"], f"{row['field']}:{row['type']}"))

    def io(code, direction):
        return ", ".join(f for d, f in fields[code] if d == direction)

    workflow_of = {}
    for row in r["execution_topology"]:
        if row["node_type"] == "IN":
            workflow_of[row["node"]] = short(row["workflow"])

    mandate = {
        "build_order": build_order,
        "critical_path": [{"position": str(i), "code": c} for i, c in enumerate(longest, 1)],
        "mandate_artifact_summary": [{"action": "NEW", "count": str(len(new)), "description": desc}],
        "field_declarations": [{"code": c, "subdomain_field": sub} for c in new],
        "new_capabilities": [{"code": c, "purpose": a["summary"], "inputs": io(c, "INPUT"),
                              "outputs": io(c, "OUTPUT")}
                             for a in r["new_artifacts"] if a["family"] == "CT" for c in [a["code"]]],
        "new_intents": [{"code": c, "purpose": a["summary"], "workflow": workflow_of[c],
                         "inputs": io(c, "INPUT")}
                        for a in r["new_artifacts"] if a["family"] == "IN" for c in [a["code"]]],
        "cross_subdomain_notes": [],
    }
    out = {"document": {"phase": "p8", "domain": domain, "subdomain": sub,
                        "cr": doc["document"]["cr"],
                        "rule_set": "transformation.schemas.REGISTER_SCHEMA_P8_V0"},
           "registers": mandate}
    OUT.write_text("# Authoring Mandate — webmail / mailbox\n\n## Machine\n\n```yaml\n"
                   + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=120)
                   + "```\n\nGenerated by `generate_p8.py` in this dossier from its P7.\n")
    print(f"wrote {OUT.name}")


if __name__ == "__main__":
    main()
